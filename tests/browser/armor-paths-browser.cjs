'use strict';
// Real menus, combat inputs and checkpoint reload in a fresh, disposable browser.
const {chromium}=require('./playwright-runtime.cjs');
const fs=require('node:fs'),assert=require('node:assert/strict');
const out='build/screenshots/armor-paths-web';fs.mkdirSync(out,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
 const report={passed:false,errors:[],cases:[]};
 try{
  const p=await browser.newPage({viewport:{width:1440,height:900}});
  p.on('pageerror',e=>report.errors.push(e.message));p.on('console',m=>{if(m.type()==='error')report.errors.push(m.text())});
  const state=()=>p.evaluate(()=>window.__godotState);
  const action=(name,value)=>p.evaluate(({name,value})=>__godotAction(name,value),{name,value});
  const wait=(fn,arg=null)=>p.waitForFunction(fn,arg,{timeout:30000});
  await p.goto(process.env.GODOT_TEST_URL||'http://127.0.0.1:4188/?v=armor-paths');
  await p.waitForFunction(()=>window.__godotState?.ready,null,{timeout:180000});
  const styles={azure_empyrea:'az_balance',fenghuang:'ph_turn',shadow_knight:'mo_discharge',hawk_of_the_fog:'fo_storm'};
  for(const [style,core] of Object.entries(styles)){
   await action('select_style:'+style);await wait(style=>__godotState.player.style===style,style);
   await action('trial');await wait(()=>__godotState.nightCoreChoice&&!document.querySelector('#battle-choices')?.hidden);
   assert.equal(await p.locator('.bc-select').count(),3);
   assert.equal((await state()).campaign.clockRunning,false);
   const options=(await state()).coreOptions;
   assert.ok(options.every(row=>row.style===style));
   await p.screenshot({path:out+'/'+style+'-cores.png'});
   // Each armor's full rules can be opened without selecting a core.
   await p.locator('.bc-info').first().click();await p.locator('#battle-choice-info').waitFor({state:'visible'});
   assert.ok((await p.locator('#bc-info-body').textContent()).length>15);
   await p.getByRole('button',{name:'关闭',exact:true}).click();
   const index=options.findIndex(x=>x.id===core);
   if(style==='azure_empyrea'){
    for(const size of [{width:960,height:540},{width:480,height:820}]){
     await p.setViewportSize(size);await p.waitForTimeout(180);
     const bounds=await p.locator('.bc-select').evaluateAll(nodes=>nodes.map(n=>({w:n.clientWidth,scroll:n.scrollWidth,h:n.clientHeight,sh:n.scrollHeight,font:getComputedStyle(n.querySelector('.bc-effect')).fontSize})));
     assert.ok(bounds.every(b=>b.scroll<=b.w+1&&b.sh<=b.h+1&&parseFloat(b.font)>=18));
     await p.screenshot({path:out+`/cores-${size.width}.png`});
    }
    await p.setViewportSize({width:1440,height:900});
    await p.locator('.bc-select').nth(index).focus();await p.keyboard.press('Enter');
   }else await p.locator('.bc-select').nth(index).click();
   await wait(core=>__godotState.player.armorCore===core&&__godotState.story.active,core);
   await action('story_skip');
   let offered=null;const started=Date.now();let resourceSeen=false;
   while(Date.now()-started<110000){
    const s=await state(),c=s.campaign,pl=s.player,resource=pl.armorState;
    if(c.phase==='reward'&&!s.ko.active){offered=c.rewards;break}
    assert.notEqual(c.phase,'failed','ordinary-input first encounter clears');
    if(s.stageCountdown>0||s.ended){await p.waitForTimeout(40);continue}
    const enemy=s.enemies.find(e=>e.hp>0);if(!enemy)continue;
    const gap=Math.abs(enemy.x-pl.x),dir=Math.sign(enemy.x-pl.x);
    const threat=enemy.state==='attack'&&!enemy.attack.hasHit&&gap<enemy.attack.range+.2&&enemy.attack.windup-enemy.stateTime>0&&enemy.attack.windup-enemy.stateTime<.16;
    let move=gap>1.25?dir:0,guard=false,command=null;
    if(threat){if(enemy.attack.unblockable)command='dodge';else guard=true}
    else if(['idle','move','guard'].includes(pl.state)&&gap<1.85){
     if(style==='azure_empyrea')command=resource.yin+resource.yang===3?'ability':resource.yang>0&&resource.yin===0?'heavy':'light';
     else if(style==='fenghuang')command=pl.skillCooldown<=0&&resource.branch===pl.stance?'ability':'heavy';
     else if(style==='hawk_of_the_fog')command=pl.fogCharges===3?'heavy':pl.skillCooldown<=0?'ability':'light';
     else command=pl.skillCooldown<=0?'ability':'light';
    }else if(pl.state==='attack'&&pl.attack.name==='light')command=style==='azure_empyrea'&&resource.yin===0?'heavy':'light';
    resourceSeen ||= resource.yin+resource.yang>0||resource.prana>0||resource.conductUntil>s.time||resource.flashUntil>s.time;
    await p.evaluate(({move,guard,command})=>{__godotAction('move',move);__godotAction('guard_held',guard);if(command)__godotAction(command)},{move,guard,command});
    await p.waitForTimeout(35);
   }
   assert.ok(offered,'reward screen reached');assert.ok(resourceSeen,'armor resource generated by actual contacts');
   await wait(()=>document.querySelector('#bc-title')?.textContent==='选择强化');
   assert.equal(await p.getByRole('button',{name:/选取并继续/}).count(),3);
   const first=offered.map(x=>x.id);
   await p.getByRole('button',{name:/更换三项强化/}).click();
   await wait(()=>__godotState.campaign.rerollsRemaining===1);
   offered=(await state()).campaign.rewards;assert.ok(offered.every(x=>!first.includes(x.id)));
   const selected=offered.findIndex(x=>x.core===core);assert.ok(selected>=0,'reroll retains own compatible option');
   assert.ok(offered.every(x=>!x.core||x.core===core));
   await p.screenshot({path:out+'/'+style+'-rewards.png'});
   if(style==='azure_empyrea'){
    await p.setViewportSize({width:480,height:820});await p.waitForTimeout(150);await p.screenshot({path:out+'/rewards-480.png'});
    assert.equal(await p.locator('.bc-select').count(),3);await p.setViewportSize({width:1440,height:900});
   }
   await p.keyboard.press(String(selected+1));
   await wait(()=>__godotState.campaign.stageIndex===1&&__godotState.campaign.phase==='fight');
   if((await state()).story.active)await action('story_skip');
   await action('menu');await wait(()=>__godotState.campaign.phase==='menu');
   await p.reload();await p.waitForFunction(()=>window.__godotState?.ready,null,{timeout:180000});
   await action('continue');await wait(core=>__godotState.player.armorCore===core&&__godotState.campaign.stageIndex===1,core);
   assert.ok((await state()).player.armorPerks[offered[selected].id]);
   report.cases.push({style,core,card:offered[selected].id,resourceSeen,resume:true});console.log('ARMOR_BROWSER '+JSON.stringify(report.cases.at(-1)));
   await action('menu');await wait(()=>__godotState.campaign.phase==='menu');
  }
  assert.deepEqual(report.errors,[]);report.passed=true;
 }finally{fs.writeFileSync(out+'/report.json',JSON.stringify(report,null,2));await browser.close()}
 console.log('ARMOR_BROWSER_PASS');
})().catch(e=>{console.error(e);process.exitCode=1});
