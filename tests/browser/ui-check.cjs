const {chromium}=require('./playwright-runtime.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist']});
 try {
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
  await page.goto('http://127.0.0.1:4187/');
  await page.waitForFunction(()=>window.__godotState?.ready,null,{timeout:60000});
  // All actions use the visible Godot UI, rather than the debug action bridge.
  await page.mouse.click(260,595);
  await page.waitForFunction(()=>__godotState.started);
  await page.mouse.click(1320,107);
  await page.waitForFunction(()=>__godotState.training);
  const initial=await page.evaluate(()=>__godotState.player.x);
  await page.mouse.move(180,662);await page.mouse.down();await page.waitForFunction(()=>Math.abs(__godotState.enemy.x-__godotState.player.x)<1.25);await page.mouse.up();
  await page.waitForFunction(x=>__godotState.player.x>x+.7,initial);
  await page.mouse.click(1305,779);
  await page.waitForFunction(()=>__godotState.enemy.hp<100);
  await page.waitForFunction(()=>__godotState.player.state==='idle');
  await page.mouse.move(1385,667);await page.mouse.down();
  await page.waitForFunction(()=>__godotState.player.state==='guard');
  await page.mouse.up();await page.waitForFunction(()=>__godotState.player.state==='idle');
  await page.mouse.click(1275,638);
  await page.waitForFunction(()=>__godotState.ultimate);
  await page.waitForFunction(()=>!__godotState.ultimate);
  await page.mouse.click(1355,52);
  await page.waitForFunction(()=>__godotState.paused);
  await page.mouse.click(260,525);
  await page.waitForFunction(()=>!__godotState.paused);
  await page.mouse.click(1355,52);
  await page.waitForFunction(()=>__godotState.paused);
  await page.mouse.click(260,595);
  await page.waitForFunction(()=>!__godotState.paused&&__godotState.enemy.hp===100);
  assert.equal(await page.evaluate(()=>__godotState.training),true,'Restart from the visible practice menu keeps training mode');
  await page.mouse.click(1355,52);
  await page.waitForFunction(()=>__godotState.paused);
  await page.mouse.click(260,649);
  await page.waitForFunction(()=>__godotState.campaign.phase==='menu'&&!__godotState.started);
  await page.mouse.click(260,595);
  await page.waitForFunction(()=>__godotState.started&&__godotState.campaign.mode==='practice');
  assert.equal(await page.evaluate(()=>__godotState.training),false,'A fresh practice session starts with live AI');
  await page.mouse.click(1355,52);
  await page.waitForFunction(()=>__godotState.paused);
  await page.mouse.click(260,649);
  await page.waitForFunction(()=>__godotState.campaign.phase==='menu');
  await page.mouse.click(260,525);
  await page.waitForFunction(()=>__godotState.campaign.mode==='trial'&&__godotState.stageCountdown>0);
  assert.equal(await page.evaluate(()=>__godotState.time),0,'The encounter intro pauses combat');
  await page.waitForTimeout(600);
  await page.screenshot({path:path.resolve(__dirname,'../../build/screenshots/trial/opening-final.png')});
  assert.equal(errors.length,0);
  fs.writeFileSync(path.resolve(__dirname,'../../build/screenshots/ui-report.json'),JSON.stringify({passed:true,errors,checks:['start','training toggle','hold movement','attack','hold guard','ultimate','pause','resume','restart','preserve training on restart','return to menu','fresh practice AI','start trial','intro pauses combat']},null,2));
  console.log('PASS: visible UI combat controls, pause/resume, practice preferences, menu round-trip and trial introduction');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
